const PARTIAL_FAMILIES = ['ዲቃላ'];

const run = async () => {
  try {
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('✅ MongoDB Connected');

    await GeezAlphabet.deleteMany({});
    console.log('🗑️  Cleared old alphabet data');

    for (const l of ALPHABET) {
      await GeezAlphabet.create({
        char: l.char,
        order: l.order,
        family: l.family,
        forms: {
          ግዕዝ: l.ግዕዝ,
          ካዕብ: l.ካዕብ,
          ሣልስ: l.ሣልስ,
          ራብዕ: l.ራብዕ,
          ሓምስ: l.ሓምስ,
          ሳድስ: l.ሳድስ,
          ሳብዕ: l.ሳብዕ,
        },
        hasFullSeven: !PARTIAL_FAMILIES.includes(l.family),
        pronunciation: { am: l.am },
        exampleWord: {
          geez: l.example,
          amharic: l.example,
        },
      });
    }

    console.log(`✅ Seeded ${ALPHABET.length} Geez letters`);
    process.exit(0);
  } catch (err) {
    console.error('❌ Seed error:', err.message);
    process.exit(1);
  }
};

run();